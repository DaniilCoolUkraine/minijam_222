using System;
using System.Collections.Generic;
using System.IO;
using ShapeInventory.Core;
using ShapeInventory.Game;
using ShapeInventory.UI.Common;
using UnityEditor;
using UnityEngine;
using Object = UnityEngine.Object;

namespace ShapeInventory.Editor
{
    /// <summary>
    /// Idempotent content generator. Existing assets are loaded and modified through SerializedObject so their GUIDs
    /// (and therefore every scene/asset reference) survive; missing assets are created. Object sprites are only
    /// generated when the PNG is missing, so real art is never overwritten.
    /// </summary>
    internal static class SampleContentBuilder
    {
        internal const string ContentRoot = "Assets/Content";
        internal const string ItemsDir = "Assets/Content/Items";
        internal const string ObjectsDir = "Assets/Content/Objects";
        internal const string LevelsDir = "Assets/Content/Levels";
        internal const string SpritesDir = "Assets/Content/Sprites";

        private const int SpriteCellPixels = 16;
        private const int MaxObjectCells = 12;

        // Generated by earlier versions of the sample content (the five-level demo). Removed when no longer part of the data.
        private static readonly string[] LegacyLevelNames =
            { "Level_01_Rocket", "Level_02_Tree", "Level_03_Boat", "Level_04_House", "Level_05_Cat" };
        private static readonly string[] LegacyObjectIds = { "rocket", "tree", "boat", "house", "cat" };
        // Plain item ids that were ever generated: enchanted copies Item_<enchantment>_<one of these> are safe to delete.
        private static readonly string[] LegacyPlainIds =
            { "i4", "i4v", "o", "t", "s", "z", "l", "j", "dot", "domino", "dominov", "i3", "i3v", "l3" };

        private static int _created;
        private static int _updated;
        private static int _moved;
        private static int _deleted;

        /// <summary>Creates / updates all content, removes obsolete generated assets and syncs the levels into Main.unity.</summary>
        internal static void Run()
        {
            Run(true);
        }

        internal static void Run(bool syncScene)
        {
            _created = 0;
            _updated = 0;
            _moved = 0;
            _deleted = 0;

            ContentUtil.EnsureFolder(ContentRoot);
            ContentUtil.EnsureFolder(ItemsDir);
            ContentUtil.EnsureFolder(ObjectsDir);
            ContentUtil.EnsureFolder(LevelsDir);
            ContentUtil.EnsureFolder(SpritesDir);

            // ---- items (plain first, then enchanted copies of the same shapes)
            var items = new Dictionary<string, ItemData>();
            var plainDefs = new Dictionary<string, ItemDef>();
            var currentItemIds = new HashSet<string>();

            foreach (ItemDef def in SampleContentData.PlainItems)
            {
                if (plainDefs.ContainsKey(def.Id))
                {
                    Debug.LogWarning("ShapeInventory: duplicate plain item id '" + def.Id + "' in the sample data (last one wins).");
                }

                plainDefs[def.Id] = def;
                currentItemIds.Add(def.Id);
                items[def.Id] = UpsertItem("Item_" + def.Id, def.Id, def.Name, ContentUtil.ParseColor(def.Hex),
                    EnchantmentType.None, def.Rows);
            }

            foreach (EnchantedItemDef def in SampleContentData.EnchantedItems)
            {
                currentItemIds.Add(def.Id);
                if (def.Type == EnchantmentType.None)
                {
                    Debug.LogWarning("ShapeInventory: enchanted item definition with type None ignored (base '" + def.BaseId + "').");
                    continue;
                }

                ItemDef baseDef;
                if (!plainDefs.TryGetValue(def.BaseId, out baseDef))
                {
                    Debug.LogError("ShapeInventory: unknown base shape '" + def.BaseId + "' for enchanted item " + def.Id);
                    continue;
                }

                items[def.Id] = UpsertItem("Item_" + def.Id, def.Id,
                    EnchantmentStyle.DisplayName(def.Type) + " " + baseDef.Name,
                    EnchantmentStyle.GetColor(def.Type), def.Type, baseDef.Rows);
            }

            // ---- objects + placeholder sprites
            var objects = new Dictionary<string, ObjectData>();
            var sprites = new Dictionary<string, Sprite>();
            foreach (ObjectDef def in SampleContentData.Objects)
            {
                Color color = ContentUtil.ParseColor(def.Hex);
                string path = ObjectsDir + "/Object_" + def.Id + ".asset";
                ObjectData asset = AssetDatabase.LoadAssetAtPath<ObjectData>(path);
                if (asset == null)
                {
                    asset = ObjectData.Create(def.Id, def.Name, color, def.Rows);
                    AssetDatabase.CreateAsset(asset, path);
                    _created++;
                }
                else
                {
                    _updated++;
                }

                var so = new SerializedObject(asset);
                so.FindProperty("id").stringValue = def.Id;
                so.FindProperty("displayName").stringValue = def.Name;
                so.FindProperty("silhouetteColor").colorValue = color;
                ContentUtil.SetStringArray(so.FindProperty("silhouetteRows"), def.Rows);
                so.ApplyModifiedPropertiesWithoutUndo();
                EditorUtility.SetDirty(asset);
                objects[def.Id] = asset;
                WarnIfTooBig(def);
                sprites[def.Id] = EnsureObjectSprite(def, asset);
            }

            // ---- levels (the first levels adopt legacy level assets so scene references keep working)
            var legacySpritePaths = new HashSet<string>();
            foreach (string legacyId in LegacyObjectIds)
            {
                if (!objects.ContainsKey(legacyId)) legacySpritePaths.Add(SpritePath(legacyId));
            }

            var currentLevelNames = new HashSet<string>();
            foreach (LevelDef def in SampleContentData.Levels) currentLevelNames.Add(def.AssetName);

            for (int index = 0; index < SampleContentData.Levels.Length; index++)
            {
                LevelDef def = SampleContentData.Levels[index];
                string path = LevelsDir + "/" + def.AssetName + ".asset";

                if (index < LegacyLevelNames.Length && !currentLevelNames.Contains(LegacyLevelNames[index])
                    && IsMissing(path))
                {
                    string legacyPath = LevelsDir + "/" + LegacyLevelNames[index] + ".asset";
                    if (!IsMissing(legacyPath))
                    {
                        string error = AssetDatabase.MoveAsset(legacyPath, path);
                        if (string.IsNullOrEmpty(error)) _moved++;
                        else Debug.LogWarning("ShapeInventory: could not move " + legacyPath + " -> " + path + ": " + error);
                    }
                }

                ObjectData target;
                if (!objects.TryGetValue(def.ObjectId, out target))
                {
                    Debug.LogError("ShapeInventory: unknown object '" + def.ObjectId + "' in " + def.AssetName);
                    continue;
                }

                LevelData asset = AssetDatabase.LoadAssetAtPath<LevelData>(path);
                if (asset == null)
                {
                    asset = LevelData.Create(def.AssetName, null, null);
                    AssetDatabase.CreateAsset(asset, path);
                    _created++;
                }
                else
                {
                    _updated++;
                }

                // A moved asset still carries its old internal name.
                if (asset.name != def.AssetName) asset.name = def.AssetName;

                var so = new SerializedObject(asset);
                so.FindProperty("targetObject").objectReferenceValue = target;

                SerializedProperty arr = so.FindProperty("startingItems");
                arr.arraySize = def.ItemIds.Length;
                for (int i = 0; i < def.ItemIds.Length; i++)
                {
                    ItemData item;
                    if (!items.TryGetValue(def.ItemIds[i], out item))
                        Debug.LogError("ShapeInventory: unknown item '" + def.ItemIds[i] + "' in " + def.AssetName);
                    arr.GetArrayElementAtIndex(i).objectReferenceValue = item;
                }

                // Only fill the sprite when nothing (or a placeholder of a removed legacy object) is assigned:
                // a hand-assigned picture always wins.
                SerializedProperty spriteProp = so.FindProperty("objectSprite");
                Object currentSprite = spriteProp.objectReferenceValue;
                bool replaceSprite = currentSprite == null
                                     || legacySpritePaths.Contains(AssetDatabase.GetAssetPath(currentSprite));
                Sprite sprite;
                if (replaceSprite && sprites.TryGetValue(def.ObjectId, out sprite) && sprite != null)
                    spriteProp.objectReferenceValue = sprite;

                so.FindProperty("questDescription").stringValue = def.Story;

                SerializedProperty reqs = so.FindProperty("requirements");
                reqs.arraySize = def.Requirements.Length;
                for (int i = 0; i < def.Requirements.Length; i++)
                {
                    SerializedProperty element = reqs.GetArrayElementAtIndex(i);
                    element.FindPropertyRelative("type").intValue = (int)def.Requirements[i].Type;
                    element.FindPropertyRelative("tier").intValue = def.Requirements[i].Tier;
                }

                so.FindProperty("successText").stringValue = def.SuccessText;
                so.FindProperty("partialText").stringValue = def.PartialText;
                so.FindProperty("failureText").stringValue = def.FailureText;

                so.ApplyModifiedPropertiesWithoutUndo();
                EditorUtility.SetDirty(asset);
            }

            AssetDatabase.SaveAssets();

            // ---- obsolete generated assets
            DeleteObsolete(currentItemIds, plainDefs, objects, currentLevelNames);

            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();

            Debug.Log("ShapeInventory: sample content up to date under " + ContentRoot + " ("
                      + (SampleContentData.PlainItems.Length + SampleContentData.EnchantedItems.Length) + " items, "
                      + SampleContentData.Objects.Length + " objects, " + SampleContentData.Levels.Length + " levels). "
                      + "Created " + _created + ", updated " + _updated + ", moved " + _moved + ", deleted " + _deleted + ".");

            if (syncScene) ContentSceneSync.SyncLevelsIntoMainScene();
        }

        /// <summary>The current campaign levels in data order (missing assets are skipped with a warning).</summary>
        internal static List<LevelData> LoadCampaignLevels(bool warnOnMissing)
        {
            var result = new List<LevelData>();
            foreach (LevelDef def in SampleContentData.Levels)
            {
                string path = LevelsDir + "/" + def.AssetName + ".asset";
                var level = AssetDatabase.LoadAssetAtPath<LevelData>(path);
                if (level != null) result.Add(level);
                else if (warnOnMissing) Debug.LogWarning("ShapeInventory: level asset missing: " + path);
            }

            return result;
        }

        // ------------------------------------------------------------------ cleanup

        private static string SpritePath(string objectId)
        {
            return SpritesDir + "/Object_" + objectId + ".png";
        }

        private static bool IsMissing(string assetPath)
        {
            return string.IsNullOrEmpty(AssetDatabase.AssetPathToGUID(assetPath));
        }

        private static void DeleteAssetIfPresent(string assetPath)
        {
            if (IsMissing(assetPath)) return;
            if (AssetDatabase.DeleteAsset(assetPath)) _deleted++;
            else Debug.LogWarning("ShapeInventory: could not delete obsolete asset " + assetPath);
        }

        /// <summary>
        /// Deletes ONLY generated leftovers: legacy levels / objects / placeholder sprites that are not in the current data and
        /// enchanted copies Item_&lt;enchantment&gt;_&lt;base&gt; that are not in the current data. Plain items and everything
        /// else (the user's own art and assets) are never touched.
        /// </summary>
        private static void DeleteObsolete(HashSet<string> currentItemIds, Dictionary<string, ItemDef> plainDefs,
            Dictionary<string, ObjectData> objects, HashSet<string> currentLevelNames)
        {
            foreach (string name in LegacyLevelNames)
            {
                if (!currentLevelNames.Contains(name)) DeleteAssetIfPresent(LevelsDir + "/" + name + ".asset");
            }

            foreach (string id in LegacyObjectIds)
            {
                if (objects.ContainsKey(id)) continue;
                DeleteAssetIfPresent(ObjectsDir + "/Object_" + id + ".asset");
                DeleteAssetIfPresent(SpritePath(id));
            }

            var knownBases = new HashSet<string>(LegacyPlainIds);
            foreach (string id in plainDefs.Keys) knownBases.Add(id);

            var toDelete = new List<string>();
            string[] guids = AssetDatabase.FindAssets("t:ItemData", new[] { ItemsDir });
            foreach (string guid in guids)
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (string.IsNullOrEmpty(path) || Path.GetExtension(path) != ".asset") continue;
                if (Path.GetDirectoryName(path).Replace('\\', '/') != ItemsDir) continue;

                string fileName = Path.GetFileNameWithoutExtension(path);
                if (!fileName.StartsWith("Item_", StringComparison.Ordinal)) continue;
                string id = fileName.Substring("Item_".Length);
                if (currentItemIds.Contains(id)) continue;

                EnchantmentType type;
                string baseId;
                if (!TryParseEnchantedId(id, out type, out baseId)) continue;
                if (!knownBases.Contains(baseId)) continue;

                var item = AssetDatabase.LoadAssetAtPath<ItemData>(path);
                if (item == null || item.Enchantment != type) continue;
                toDelete.Add(path);
            }

            foreach (string path in toDelete) DeleteAssetIfPresent(path);
        }

        /// <summary>"sharpness_i4" -> (Sharpness, "i4"). The lowercase enchantment name (never None) plus '_' plus [a-z0-9_]+.</summary>
        private static bool TryParseEnchantedId(string id, out EnchantmentType type, out string baseId)
        {
            foreach (EnchantmentType candidate in Enum.GetValues(typeof(EnchantmentType)))
            {
                if (candidate == EnchantmentType.None) continue;
                string prefix = candidate.ToString().ToLowerInvariant() + "_";
                if (!id.StartsWith(prefix, StringComparison.Ordinal) || id.Length == prefix.Length) continue;

                string rest = id.Substring(prefix.Length);
                bool valid = true;
                for (int i = 0; i < rest.Length; i++)
                {
                    char c = rest[i];
                    if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '_'))
                    {
                        valid = false;
                        break;
                    }
                }

                if (!valid) continue;
                type = candidate;
                baseId = rest;
                return true;
            }

            type = EnchantmentType.None;
            baseId = null;
            return false;
        }

        private static void WarnIfTooBig(ObjectDef def)
        {
            int width = 0;
            foreach (string row in def.Rows) width = Mathf.Max(width, row.Length);
            if (width > MaxObjectCells || def.Rows.Length > MaxObjectCells)
                Debug.LogWarning("ShapeInventory: object '" + def.Id + "' is " + width + "x" + def.Rows.Length
                                 + " cells (more than " + MaxObjectCells + "x" + MaxObjectCells + "); the layout may get cramped.");
        }

        // ------------------------------------------------------------------ items

        private static ItemData UpsertItem(string assetName, string id, string displayName, Color color,
            EnchantmentType enchantment, string[] rows)
        {
            string path = ItemsDir + "/" + assetName + ".asset";
            ItemData asset = AssetDatabase.LoadAssetAtPath<ItemData>(path);
            if (asset == null)
            {
                asset = ItemData.Create(id, displayName, color, enchantment, rows);
                AssetDatabase.CreateAsset(asset, path);
                _created++;
            }
            else
            {
                _updated++;
            }

            var so = new SerializedObject(asset);
            so.FindProperty("id").stringValue = id;
            so.FindProperty("displayName").stringValue = displayName;
            so.FindProperty("color").colorValue = color;
            so.FindProperty("enchantment").intValue = (int)enchantment;
            ContentUtil.SetStringArray(so.FindProperty("shapeRows"), rows);
            so.ApplyModifiedPropertiesWithoutUndo();
            EditorUtility.SetDirty(asset);
            return asset;
        }

        // ------------------------------------------------------------------ placeholder sprites

        /// <summary>
        /// Returns the sprite at Assets/Content/Sprites/Object_&lt;id&gt;.png. The PNG (16x16 px per silhouette cell) is generated
        /// only if the file does not exist yet; an existing file is never touched.
        /// </summary>
        private static Sprite EnsureObjectSprite(ObjectDef def, ObjectData data)
        {
            string assetPath = SpritePath(def.Id);
            string projectRoot = Path.GetDirectoryName(Application.dataPath);
            string diskPath = Path.Combine(projectRoot, assetPath);

            if (!File.Exists(diskPath))
            {
                byte[] png = RenderPlaceholderPng(data, ContentUtil.ParseColor(def.Hex), def.Id);
                File.WriteAllBytes(diskPath, png);
                AssetDatabase.ImportAsset(assetPath, ImportAssetOptions.ForceSynchronousImport | ImportAssetOptions.ForceUpdate);

                var importer = AssetImporter.GetAtPath(assetPath) as TextureImporter;
                if (importer != null)
                {
                    importer.textureType = TextureImporterType.Sprite;
                    importer.spriteImportMode = SpriteImportMode.Single;
                    importer.spritePixelsPerUnit = SpriteCellPixels;
                    importer.filterMode = FilterMode.Point;
                    importer.alphaIsTransparency = true;
                    importer.mipmapEnabled = false;
                    importer.textureCompression = TextureImporterCompression.Uncompressed;
                    importer.SaveAndReimport();
                }
            }
            else if (AssetDatabase.LoadAssetAtPath<Texture2D>(assetPath) == null)
            {
                // File exists on disk but Unity has not imported it yet (e.g. dropped in from outside): import with its own settings.
                AssetDatabase.ImportAsset(assetPath, ImportAssetOptions.ForceSynchronousImport);
            }

            Sprite sprite = AssetDatabase.LoadAssetAtPath<Sprite>(assetPath);
            if (sprite == null)
                Debug.LogWarning("ShapeInventory: " + assetPath + " is not imported as a Sprite (Single); set its Texture Type to Sprite to use it.");
            return sprite;
        }

        private static byte[] RenderPlaceholderPng(ObjectData data, Color baseColor, string objectId)
        {
            ItemShape sil = data.Silhouette;
            int w = sil.Width * SpriteCellPixels;
            int h = sil.Height * SpriteCellPixels;
            var pixels = new Color32[w * h];

            float baseHue, baseSat, baseVal;
            Color.RGBToHSV(baseColor, out baseHue, out baseSat, out baseVal);
            // A different stripe style per object so the placeholders do not look identical.
            int style = 0;
            for (int i = 0; i < objectId.Length; i++) style += objectId[i];
            style %= 3;

            for (int y = 0; y < h; y++)
            {
                for (int x = 0; x < w; x++)
                {
                    // y is measured from the TOP of the picture; Texture2D rows run bottom-up.
                    int index = (h - 1 - y) * w + x;
                    if (!InsideSilhouette(sil, x, y, w, h))
                    {
                        pixels[index] = new Color32(0, 0, 0, 0);
                        continue;
                    }

                    float u = w > 1 ? x / (float)(w - 1) : 0f;
                    float v = h > 1 ? y / (float)(h - 1) : 0f;

                    float hue = Mathf.Repeat(baseHue + 0.18f * v + 0.08f * u, 1f);
                    float sat = Mathf.Clamp01(Mathf.Max(baseSat, 0.45f) + 0.15f * u);
                    float val = Mathf.Lerp(1f, 0.72f, v);

                    bool stripe;
                    if (style == 0) stripe = ((x + y) / 6) % 2 == 0;
                    else if (style == 1) stripe = (x / 8) % 2 == 0;
                    else stripe = ((x / 8) + (y / 8)) % 2 == 0;
                    if (stripe) val *= 0.9f;

                    bool edge = !InsideSilhouette(sil, x - 2, y, w, h) || !InsideSilhouette(sil, x + 2, y, w, h)
                                || !InsideSilhouette(sil, x, y - 2, w, h) || !InsideSilhouette(sil, x, y + 2, w, h);
                    if (edge) val *= 0.55f;

                    Color c = Color.HSVToRGB(hue, sat, Mathf.Clamp01(val));
                    pixels[index] = new Color32(
                        (byte)Mathf.RoundToInt(c.r * 255f),
                        (byte)Mathf.RoundToInt(c.g * 255f),
                        (byte)Mathf.RoundToInt(c.b * 255f),
                        255);
                }
            }

            var tex = new Texture2D(w, h, TextureFormat.RGBA32, false);
            tex.SetPixels32(pixels);
            tex.Apply();
            byte[] png = tex.EncodeToPNG();
            Object.DestroyImmediate(tex);
            return png;
        }

        private static bool InsideSilhouette(ItemShape sil, int px, int py, int w, int h)
        {
            if (px < 0 || py < 0 || px >= w || py >= h) return false;
            return sil.Contains(new Vector2Int(px / SpriteCellPixels, py / SpriteCellPixels));
        }
    }
